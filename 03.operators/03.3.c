// problem 03: Comparison operators

#include<stdio.h>

int main()
{
    int a = 10,b = 20;
    printf("%d,%d\n", a,b);
    printf("a==b : %d\n", a==b);
    printf("a!=b : %d\n", a!=b);
    printf("a>b : %d\n", a>b);
    printf("a<b : %d\n", a<b);
    printf("a>=b : %d\n", a>=b);
    printf("a<=b : %d\n", a<=b);
    return 0;

}
