//1. Write a program to calculate the sum, difference, and product of three integers.

#include<stdio.h>

int main ()
{
    int a, b, c;
    a = 5, b = 2, c= 3;
    printf("sum = %d\n", a + b + c);
    printf("difference = %d\n", a - b - c);
    printf("product = %d\n", a * b * c);
    return 0;
}
